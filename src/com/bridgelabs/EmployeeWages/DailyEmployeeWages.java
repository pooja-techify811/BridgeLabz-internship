package com.bridgelabs.EmployeeWages;

public class DailyEmployeeWages {

    public static void main(String[] args) {

        int wagePerHour = 20;
        int fullDayHours = 8;

        int dailyWage = wagePerHour * fullDayHours;

        System.out.println("Daily Employee Wage: " + dailyWage);
    }
}
